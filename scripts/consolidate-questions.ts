import { createHash } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { bankV71 } from "../src/content/questions/archive/bank-v71";
import { questions1500 } from "../src/content/questions/questions-1500";
import {
  retiredQuestionIdsV72,
  approvedNewQuestionsV72,
} from "../src/content/questions/release-v72-meaning";
import type { Question } from "../src/content/questions/model";
import baseline from "../tests/fixtures/content/pre-consolidation-v71.json";
import { questionSnapshot } from "./question-snapshot";

const frozenV71 = new URL(
  "../src/content/questions/questions-1500.ts",
  import.meta.url,
);
const destinationV72 = new URL(
  "../src/content/questions/questions-v72.ts",
  import.meta.url,
);

// Reproduce v71 from its immutable archive; never edit that historical snapshot.
export function canonicalQuestionSource(): string {
  const literal = questionSnapshot(bankV71);
  const digest = createHash("sha256").update(literal).digest("hex");
  if (bankV71.length !== 1500 || digest !== baseline.banks[71].sha256)
    throw new Error(
      "Frozen v71 baseline changed; investigate before regeneration",
    );
  return `// Generated by pnpm questions:generate from the immutable v71 archive.\n// All 1,500 current records are physically here; no runtime content imports.\n// Baseline SHA-256: ${digest}\nimport type { Question } from "./model";\n\nexport const questions1500: readonly Question[] = ${literal};\n`;
}

export function composedQuestionsV72(): readonly Question[] {
  if (
    retiredQuestionIdsV72.length !== 30 ||
    approvedNewQuestionsV72.length !== 30 ||
    new Set(retiredQuestionIdsV72).size !== 30
  )
    throw new Error("v72 requires exactly 30 unique replacements");

  const priorIds = new Set(questions1500.map((q) => q.id));
  const replacements = new Map<string, Question>(
    retiredQuestionIdsV72.map((id, index) => [
      id,
      approvedNewQuestionsV72[index]!,
    ]),
  );
  if (
    retiredQuestionIdsV72.some((id) => !priorIds.has(id)) ||
    approvedNewQuestionsV72.some(
      (q) =>
        q.categoryId !== "quran" ||
        q.version !== 72 ||
        q.reviewStatus !== "approved" ||
        q.sources.length === 0 ||
        q.sources.some((s) => s.checkStatus !== "supported"),
    )
  )
    throw new Error("v72 replacement provenance or status invalid");

  const next = questions1500.map((q) => replacements.get(q.id) ?? q);
  if (next.length !== 1500 || new Set(next.map((q) => q.id)).size !== 1500)
    throw new Error("v72 ID collision or count mismatch");
  return next;
}

export function canonicalV72Source(): string {
  const literal = questionSnapshot(composedQuestionsV72());
  return `// Generated by pnpm questions:generate. v72 preserves v71 as frozen history.\n// The current 1,500 records are literal; do not hand-edit this file.\n// Exactly 30 source-linked Quran meaning questions replace 30 rote facts.\nimport type { Question } from "./model";\n\nexport const questionsV72: readonly Question[] = ${literal};\n`;
}

async function main() {
  const args = process.argv.slice(2);
  if (args.length !== 1 || !["--write", "--check"].includes(args[0]!))
    throw new Error(
      "Usage: tsx scripts/consolidate-questions.ts --write|--check",
    );
  const v71 = canonicalQuestionSource();
  const v72 = canonicalV72Source();
  if (args[0] === "--write") {
    await writeFile(frozenV71, v71);
    await writeFile(destinationV72, v72);
    console.log("Generated v71 history and v72 current: 1,500 questions.");
  } else {
    if ((await readFile(frozenV71, "utf8")) !== v71)
      throw new Error("Frozen v71 canonical file differs from its archive");
    if ((await readFile(destinationV72, "utf8")) !== v72)
      throw new Error("v72 canonical file is stale; run pnpm questions:generate");
    console.log("Frozen v71 and active v72 canonical files match exactly.");
  }
}

if (
  process.argv[1] &&
  resolve(process.argv[1]) === fileURLToPath(import.meta.url)
) {
  void main().catch((error: unknown) => {
    console.error(
      error instanceof Error ? error.message : "Question generation failed",
    );
    process.exitCode = 1;
  });
}
